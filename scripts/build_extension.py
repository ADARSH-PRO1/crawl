"""Build the browser extension for every supported browser family from one source tree.

    python scripts/build_extension.py            # dist/chromium and dist/firefox
    python scripts/build_extension.py --zip      # also store-ready zips in dist/
    python scripts/build_extension.py --test     # dist/chromium-test: adds <all_urls> so automated tests can inject

The list detector is NOT copied by hand: detect.js is generated from app/scrape_detect.js (the file the crawler uses), so
the app and the extension always find the same lists.
"""
import argparse
import json
import shutil
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "extension" / "src"
ICONS = ROOT / "extension" / "icons"
DETECTOR = ROOT / "app" / "scrape_detect.js"
DIST = ROOT / "dist"
TARGETS = ("chromium", "firefox")
ICON_SIZES = (16, 32, 48, 128)

DETECT_WRAPPER = """// GENERATED by scripts/build_extension.py from app/scrape_detect.js. Do not edit here.
globalThis.__scrapeDetect = function (args) {
  return new Promise((resolve) => {
    window.__scrapeArgs = Object.assign({}, args, { onResult: resolve });
%s
  });
};
"""


def deep_merge(base: dict, patch: dict) -> dict:
    out = dict(base)
    for k, v in patch.items():
        out[k] = deep_merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def manifest_for(target: str, test: bool = False) -> dict:
    base = json.loads((SRC / "manifest.base.json").read_text(encoding="utf-8"))
    patch = json.loads((SRC / f"manifest.{target}.patch.json").read_text(encoding="utf-8"))
    manifest = deep_merge(base, patch)
    if test:  # tests cannot click the toolbar icon, so they get host access up front. Never shipped.
        manifest["host_permissions"] = ["<all_urls>"]
        manifest["name"] += " (test build)"
    return manifest


def detect_js() -> str:
    body = DETECTOR.read_text(encoding="utf-8")
    return DETECT_WRAPPER % "\n".join("    " + line if line else line for line in body.splitlines())


# ---- placeholder icons (replace the PNGs in extension/icons with real artwork any time) -------------------------
def _png(size: int) -> bytes:
    green, white = (5, 150, 105, 255), (255, 255, 255, 255)
    radius = size * 0.2
    rows = []
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            u, v = (x + 0.5) / size, (y + 0.5) / size
            cx, cy = min(max(x + 0.5, radius), size - radius), min(max(y + 0.5, radius), size - radius)
            inside = (x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= radius ** 2
            stem = 0.43 <= u <= 0.57 and 0.2 <= v <= 0.52
            head = 0.52 <= v <= 0.78 and abs(u - 0.5) <= (0.78 - v) * 0.9 + 0.0
            bar = 0.8 <= v <= 0.86 and 0.24 <= u <= 0.76
            row += bytes(white if inside and (stem or head or bar) else green if inside else (0, 0, 0, 0))
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def ensure_icons() -> None:
    ICONS.mkdir(parents=True, exist_ok=True)
    for size in ICON_SIZES:
        path = ICONS / f"{size}.png"
        if not path.exists():
            path.write_bytes(_png(size))


def build(out_root: Path = DIST, targets=TARGETS, test: bool = False, make_zip: bool = False) -> dict[str, Path]:
    """Writes one folder per target and returns {target: folder}."""
    ensure_icons()
    built = {}
    for target in targets:
        out = out_root / (f"{target}-test" if test else target)
        if out.exists():
            shutil.rmtree(out)
        out.mkdir(parents=True)
        for name in ("background.js", "content.js", "pagedetails.js"):
            shutil.copy2(SRC / name, out / name)
        shutil.copytree(SRC / "ui", out / "ui")
        shutil.copytree(SRC / "lib", out / "lib")
        shutil.copytree(ICONS, out / "icons")
        (out / "detect.js").write_text(detect_js(), encoding="utf-8")
        manifest = manifest_for(target, test)
        (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        built[target] = out
        if make_zip and not test:
            archive = shutil.make_archive(str(out_root / f"bizfy-scraper-{target}-{manifest['version']}"), "zip", out)
            print(f"[build] {archive}")
    return built


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--zip", action="store_true", help="also write store-ready zips")
    p.add_argument("--test", action="store_true", help="build the test variant (adds <all_urls>)")
    p.add_argument("--target", choices=TARGETS, action="append", help="only this target (default: all)")
    args = p.parse_args(argv)
    for target, folder in build(targets=args.target or TARGETS, test=args.test, make_zip=args.zip).items():
        print(f"[build] {target}: {folder}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
